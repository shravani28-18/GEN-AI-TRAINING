def print_all_records():

    print("\n========== ALL DAIRY RECORDS ==========")

    for record in records:

        print("\nTopic:", record["topic"])
        print("Animal:", record["animal_type"])
        print("Recommendation:", record["recommendation"])
        print("Quantity/Schedule:", record["quantity_or_schedule"])
        print("Source:", record["source_doc"])
        print("Source URL:", record["source_url"])

        print("-" * 60)


# ==================================================
#              SEARCH BY KEYWORD
# ==================================================

def search_records(keyword):

    keyword = keyword.lower()

    results = []

    for record in records:

        searchable_text = " ".join(str(value) for value in record.values()).lower()

        if keyword in searchable_text:

            results.append(record)

    return results


# ==================================================
#              COUNT BY CATEGORY
# ==================================================

def count_by_category():

    category_count = {}

    for record in records:

        category = record["topic"]

        if category in category_count:

            category_count[category] += 1

        else:

            category_count[category] = 1

    print("\n== CATEGORY COUNTS ==")

    for category, count in category_count.items():

        print(category, ":", count)


